let currentLang = "tr"; // Global active language state

// Get a translated string for a key
function getTranslation(key, variables = null) {
  const lang = currentLang;
  let text = key;
  
  if (LOFI_TRANSLATIONS[lang] && LOFI_TRANSLATIONS[lang][key]) {
    text = LOFI_TRANSLATIONS[lang][key];
  } else if (LOFI_TRANSLATIONS["en"] && LOFI_TRANSLATIONS["en"][key]) {
    text = LOFI_TRANSLATIONS["en"][key];
  }
  
  if (variables) {
    Object.keys(variables).forEach(vKey => {
      text = text.replace(new RegExp(`%${vKey}%`, 'g'), variables[vKey]);
    });
  }
  
  return text;
}

// Translate dynamic playlist subtitles using backend subtitleVariants
function getResolvedSubtitle(item, lang = currentLang) {
  if (!item) return "";
  
  // Determine TimeOfDay cases (matching Swift calendar hour case ranges)
  const hour = new Date().getHours();
  let tod = "night";
  if (hour >= 6 && hour < 12) {
    tod = "morning";
  } else if (hour >= 12 && hour < 18) {
    tod = "afternoon";
  } else if (hour >= 18 && hour < 22) {
    tod = "evening";
  }
  
  const specificKey = `${lang}_${tod}`;
  if (item.subtitleVariants && item.subtitleVariants[specificKey]) {
    return item.subtitleVariants[specificKey];
  }
  
  if (item.subtitleVariants && item.subtitleVariants[lang]) {
    return item.subtitleVariants[lang];
  }
  
  const defaultKey = `en_${tod}`;
  if (item.subtitleVariants && item.subtitleVariants[defaultKey]) {
    return item.subtitleVariants[defaultKey];
  }
  
  return item.subtitle || "";
}
